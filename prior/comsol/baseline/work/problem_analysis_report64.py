def pdf_text(text):
    # Render unsupported Unicode super/subscript glyphs as explicit PDF markup.
    text=str(text).replace('𝒟','D项').replace('ᵣ','r')
    escaped=html.escape(text)
    trans=str.maketrans('⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻','0123456789+-')
    escaped=re.sub('[⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻]+',lambda m:'<super>'+m.group().translate(trans)+'</super>',escaped)
    trans2=str.maketrans('₀₁₂₃₄₅₆₇₈₉','0123456789')
    escaped=re.sub('[₀₁₂₃₄₅₆₇₈₉]+',lambda m:'<sub>'+m.group().translate(trans2)+'</sub>',escaped)
    return escaped.replace('∇','<font name="SymbolUnicode">∇</font>')
