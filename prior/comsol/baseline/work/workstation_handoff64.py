def markdown():
    out=['# '+d.NAME,'']
    for pg in d.pages:
        out+=['## '+pg['title'],'',pg['subtitle'],'']
        for b in pg['blocks']:
            if b[0] in ['p','note']:out += [b[1],'']
            elif b[0]=='table':
                out+=['| '+' | '.join(b[1])+' |','|'+'|'.join('---' for _ in b[1])+'|']
                out+=['| '+' | '.join(str(x).replace('|','/') for x in row)+' |' for row in b[2]]
                out+=['']
    return '\n'.join(out)

